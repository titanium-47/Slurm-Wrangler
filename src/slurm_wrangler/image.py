"""Container image lifecycle.

The environment spec (environment.yml + base image + apt/pip extras, or a
project Dockerfile) is content-hashed. The hash names both the local docker tag
(sw-<project>:<hash8>) and the remote SIF (env-<hash8>.sif), so:

  - `sw run` knows instantly whether the cluster already has the right image;
  - changing a dependency automatically triggers exactly one rebuild+push;
  - unchanged deps never rebuild, no matter how much code changes.
"""
from __future__ import annotations

import hashlib
import shutil
import tempfile
from pathlib import Path
from typing import Optional

from .config import ClusterConfig, ConfigError, ProjectConfig
from .remote import RemoteError, info, run_local, rsync, ssh_mkdirs, ssh_test, warn

_DOCKER_PREFIX: Optional[list] = None


def _docker_prefix() -> list:
    """[] normally; ['sudo','-n'] when the docker socket needs root (user not in
    the docker group). Cached per process."""
    global _DOCKER_PREFIX
    if _DOCKER_PREFIX is None:
        probe = run_local(["docker", "version", "--format", "ok"], check=False, capture=True)
        if probe.returncode == 0:
            _DOCKER_PREFIX = []
        else:
            probe = run_local(["sudo", "-n", "docker", "version", "--format", "ok"],
                              check=False, capture=True)
            if probe.returncode == 0:
                warn("docker needs root here (user not in the docker group) — using sudo. "
                     "Permanent fix: sudo usermod -aG docker $USER && re-login")
                _DOCKER_PREFIX = ["sudo", "-n"]
            else:
                _DOCKER_PREFIX = []  # let the real command fail with docker's error
    return _DOCKER_PREFIX


def env_hash(project: ProjectConfig) -> str:
    img = project.image
    h = hashlib.sha256()
    if img.kind == "prebuilt":
        h.update(f"prebuilt:{img.sif_remote}".encode())
        return h.hexdigest()[:8]
    if img.kind == "conda":
        env_file = project.root / img.environment
        if not env_file.exists():
            raise ConfigError(
                f"image.environment file not found: {env_file}\n"
                f"Export one with: conda env export -n <env> --no-builds > {img.environment}"
            )
        h.update(b"conda:")
        h.update(env_file.read_bytes())
        h.update(img.base.encode())
        for a in sorted(img.apt):
            h.update(f"apt:{a}".encode())
        for p in img.pip:  # pip order matters
            h.update(f"pip:{p}".encode())
    else:  # dockerfile
        df = project.root / img.dockerfile
        if not df.exists():
            raise ConfigError(f"image.dockerfile not found: {df}")
        h.update(b"dockerfile:")
        h.update(df.read_bytes())
        for k in sorted(img.build_args):
            h.update(f"arg:{k}={img.build_args[k]}".encode())
    return h.hexdigest()[:8]


def docker_tag(project: ProjectConfig, ehash: str) -> str:
    return f"sw-{project.name}:{ehash}"


def sif_name(ehash: str) -> str:
    return f"env-{ehash}.sif"


def remote_sif_path(project: ProjectConfig, cluster: ClusterConfig, ehash: str) -> str:
    if project.image.kind == "prebuilt":
        return project.image.sif_remote
    return f"{cluster.project_dir(project.name)}/images/{sif_name(ehash)}"


