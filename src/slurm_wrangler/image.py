# Build
# ---------------------------------------------------------------------------
MICROMAMBA_DOCKERFILE = """\
# Generated by slurm_wrangler — do not edit (regenerated per build).
FROM {base}
USER root
{apt_block}COPY {env_file} /tmp/environment.yml
# Env at a fixed prefix so PATH works without shell activation; `micromamba run
# -p /opt/env` (used at job runtime) additionally applies activate.d scripts.
RUN micromamba create -y -p /opt/env -f /tmp/environment.yml && micromamba clean -afy
{pip_block}ENV PATH=/opt/env/bin:$PATH \\
    MAMBA_ROOT_PREFIX=/opt/mamba \\
    PYTHONNOUSERSITE=1
"""


def _generated_dockerfile(project: ProjectConfig) -> str:
    img = project.image
    apt_block = ""
    if img.apt:
        pkgs = " ".join(sorted(img.apt))
        apt_block = (
            "RUN apt-get update && apt-get install -y --no-install-recommends "
            f"{pkgs} && rm -rf /var/lib/apt/lists/*\n"
        )
    pip_block = ""
    if img.pip:
        specs = " ".join(f"'{p}'" for p in img.pip)
        pip_block = f"RUN /opt/env/bin/python -m pip install --no-cache-dir {specs}\n"
    return MICROMAMBA_DOCKERFILE.format(
        base=img.base, env_file=Path(img.environment).name,
        apt_block=apt_block, pip_block=pip_block,
    )


def build_docker(project: ProjectConfig, ehash: str) -> str:
    """Build (or reuse) the local docker image. Returns the tag."""
    tag = docker_tag(project, ehash)
    have = run_local(_docker_prefix() + ["docker", "image", "inspect", tag], check=False, capture=True)
    if have.returncode == 0:
        info(f"docker image {tag} already built")
        return tag
    img = project.image
    if img.kind == "dockerfile":
        info(f"building {tag} from {img.dockerfile} ...")
        cmd = _docker_prefix() + ["docker", "build", "-f", str(project.root / img.dockerfile), "-t", tag]
        for k, v in img.build_args.items():
            cmd += ["--build-arg", f"{k}={v}"]
        cmd.append(str(project.root))
        run_local(cmd)
    else:
        info(f"building {tag} (micromamba + {img.environment}) ...")
        with tempfile.TemporaryDirectory() as ctx:
            ctx_path = Path(ctx)
            shutil.copy2(project.root / img.environment, ctx_path / Path(img.environment).name)
            (ctx_path / "Dockerfile").write_text(_generated_dockerfile(project))
            run_local(_docker_prefix() + ["docker", "build", "-t", tag, str(ctx_path)])
    return tag


def build_sif(project: ProjectConfig, ehash: str, exports_dir: Path) -> Path:
    """Convert the docker image into a single .sif via apptainer."""
    if shutil.which("apptainer") is None:
        raise RemoteError(
            "apptainer is not installed locally (needed to convert docker->sif).\n"
            "Install: sudo add-apt-repository -y ppa:apptainer/ppa && sudo apt install -y apptainer"
        )
    exports_dir.mkdir(parents=True, exist_ok=True)
    sif = exports_dir / sif_name(ehash)
    if sif.exists():
        info(f"SIF already converted: {sif}")
        return sif
    tag = docker_tag(project, ehash)
    info(f"converting {tag} -> {sif.name} (this can take a while) ...")
    prefix = _docker_prefix()
    # as root (sudo path) --fakeroot is both unnecessary and broken (no subuid for root)
    fakeroot = [] if prefix else ["--fakeroot"]
    run_local(prefix + ["apptainer", "build"] + fakeroot + [str(sif), f"docker-daemon://{tag}"],
              env=_env_with("APPTAINER_NOHTTPS", "1"))
    if prefix:  # sudo build leaves a root-owned file
        import getpass
        run_local(["sudo", "-n", "chown", getpass.getuser(), str(sif)])
    return sif


def _env_with(key: str, val: str):
    import os
    e = dict(os.environ)
    e[key] = val
    return e


# ---------------------------------------------------------------------------
# Push / ensure
# ---------------------------------------------------------------------------
def remote_has_image(project: ProjectConfig, cluster: ClusterConfig, ehash: str) -> bool:
    return ssh_test(cluster.login, f"-s {remote_sif_path(project, cluster, ehash)}")


def push_image(project: ProjectConfig, cluster: ClusterConfig, ehash: str) -> str:
    """Build + convert + upload if the cluster doesn't have this env hash yet."""
    remote_path = remote_sif_path(project, cluster, ehash)
    if project.image.kind == "prebuilt":
        if not ssh_test(cluster.login, f"-s {remote_path}"):
            raise RemoteError(f"prebuilt image not found on {cluster.name}: {remote_path}")
        return remote_path
    if remote_has_image(project, cluster, ehash):
        info(f"image env-{ehash} already on {cluster.name}")
        return remote_path
    build_docker(project, ehash)
    sif = build_sif(project, ehash, project.state_dir / "exports")
    ssh_mkdirs(cluster.login, [str(Path(remote_path).parent)])
    size_gb = sif.stat().st_size / (1 << 30)
    info(f"uploading {sif.name} ({size_gb:.1f} GB) -> {cluster.login} (resumable) ...")
    # rsync --partial: a dropped connection resumes instead of restarting.
    rsync(str(sif), f"{cluster.login}:{remote_path}", ["-t", "--partial", "--progress"])
    return remote_path


def ensure_image(project: ProjectConfig, cluster: ClusterConfig, *,
                 auto_build: bool = True, dry_run: bool = False) -> str:
    ehash = env_hash(project)
    remote_path = remote_sif_path(project, cluster, ehash)
    if dry_run:
        info(f"[dry-run] image env hash: {ehash} -> {remote_path}")
        return remote_path
    if project.image.kind != "prebuilt" and not remote_has_image(project, cluster, ehash):
        if not auto_build:
            raise RemoteError(
                f"image env-{ehash} is not on {cluster.name} and --no-build was given.\n"
                f"Build+push it with: sw env push"
            )
        warn(f"image env-{ehash} not on {cluster.name}; building + pushing now "
             f"(happens once per dependency change)")
        push_image(project, cluster, ehash)
    elif project.image.kind == "prebuilt":
        if not ssh_test(cluster.login, f"-s {remote_path}"):
            raise RemoteError(f"prebuilt image missing on {cluster.name}: {remote_path}")
    return remote_path
